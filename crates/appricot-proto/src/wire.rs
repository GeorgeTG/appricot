/// Why [`encode_envelope`] refused a message.
///
/// The field path names the first rule the message broke, as a dotted path from the message
/// root (`"surface_new.title"`); the names are the same on decode and on encode.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EncodeError {
    /// A field broke a cap in the limits table, or a value rule beside it (a zero scale, a
    /// zero tile codec, an empty key code, a configure serial of 0, cursor bytes that are not
    /// width * height * 4); nothing was emitted.
    LimitViolation {
        /// The offending field, as a dotted path from the message root.
        field: &'static str,
    },
    /// A field carries a value v0 does not define, an unknown enum value, or the envelope has
    /// no body; nothing was emitted.
    ProtocolViolation {
        /// The offending field, as a dotted path from the message root.
        field: &'static str,
    },
}

impl fmt::Display for EncodeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::LimitViolation { field } => write!(f, "field {field} breaks the limits table"),
            Self::ProtocolViolation { field } => write!(f, "field {field} breaks the v0 rules"),
        }
    }
}

impl std::error::Error for EncodeError {}

/// Why [`decode_envelope`] refused a message.
///
/// A field path names the first rule the message broke, exactly as in [`EncodeError`].
#[derive(Debug, Clone)]
pub enum DecodeError {
    /// The input is longer than [`MAX_MESSAGE_BYTES`]; refused before any parsing.
    TooLarge,
    /// A length or a count broke a cap in the limits table, or a decoded value broke a value
    /// rule beside it (see [`EncodeError::LimitViolation`]). A cap is checked on the raw
    /// bytes, before anything is allocated for the field.
    LimitViolation {
        /// The offending field, as a dotted path from the message root.
        field: &'static str,
    },
    /// The envelope names no message this side knows: it has no body at all, or a field
    /// number no v0 message has. v0.md §1: the receiver closes without a reply.
    UnknownMessage,
    /// The bytes break the v0 grammar: they are truncated, a length runs past its message, a
    /// known field has the wrong wire type or a varint over 32 bits, a field number is 0, a
    /// group or an undefined wire type appears, a string is not UTF-8, a field that is not
    /// repeated appears twice, the envelope carries a second body, or an enum field carries a
    /// value v0 does not define.
    ProtocolViolation {
        /// The offending field, as a dotted path from the message root, or the message.
        field: &'static str,
    },
    /// prost refused bytes the pre-scan passed. The pre-scan checks everything prost does, so
    /// this is not expected; it is kept so that no prost error is ever swallowed. prost is not
    /// part of this crate's public API.
    Decode(prost::DecodeError),
}

impl From<prost::DecodeError> for DecodeError {
    fn from(error: prost::DecodeError) -> Self {
        Self::Decode(error)
    }
}

impl fmt::Display for DecodeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::TooLarge => write!(f, "over {MAX_MESSAGE_BYTES} bytes"),
            Self::LimitViolation { field } => write!(f, "field {field} breaks the limits table"),
            Self::UnknownMessage => write!(f, "the envelope names no v0 message"),
            Self::ProtocolViolation { field } => write!(f, "field {field} breaks the v0 rules"),
            Self::Decode(e) => write!(f, "not an Envelope: {e}"),
        }
    }
}

impl std::error::Error for DecodeError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Decode(e) => Some(e),
            _ => None,
        }
    }
}

/// A rule [`check`] found broken.
enum Violation {
    /// A cap or a value rule: [`DecodeError::LimitViolation`].
    Limit(&'static str),
    /// A value v0 does not define: [`DecodeError::ProtocolViolation`].
    Protocol(&'static str),
    /// No body at all.
    NoBody,
}

impl From<Violation> for DecodeError {
    fn from(violation: Violation) -> Self {
        match violation {
            Violation::Limit(field) => Self::LimitViolation { field },
            Violation::Protocol(field) => Self::ProtocolViolation { field },
            Violation::NoBody => Self::UnknownMessage,
        }
    }
}

impl From<Violation> for EncodeError {
    fn from(violation: Violation) -> Self {
        match violation {
            Violation::Limit(field) => Self::LimitViolation { field },
            Violation::Protocol(field) => Self::ProtocolViolation { field },
            Violation::NoBody => Self::ProtocolViolation { field: "body" },
        }
    }
}

impl From<Refusal> for DecodeError {
    fn from(refusal: Refusal) -> Self {
        match refusal {
            Refusal::Limit(field) => Self::LimitViolation { field },
            Refusal::Grammar(field) => Self::ProtocolViolation { field },
            Refusal::UnknownMessage => Self::UnknownMessage,
        }
    }
}

/// Checks `envelope` against every rule one message can break: the rows of the limits table,
/// the value rules beside them, and the closed enum sets.
///
/// Returns the first broken rule as [`DecodeError::LimitViolation`] or
/// [`DecodeError::ProtocolViolation`]. An `Envelope` whose oneof names no body is
/// [`DecodeError::UnknownMessage`]: v0 has no body-less envelope.
///
/// Rows that bound living session state ([`crate::limits::MAX_SURFACES`] and friends) are not
/// decidable from one message and are the streamer's to check.
pub fn validate_envelope(envelope: &Envelope) -> Result<(), DecodeError> {
    check(envelope).map_err(DecodeError::from)
}

/// Encodes one `Envelope` as the bytes of one WebSocket binary message.
///
/// Fails with [`EncodeError::LimitViolation`] when any field breaks the limits table or a
/// value rule, and with [`EncodeError::ProtocolViolation`] on an enum value v0 does not
/// define or a missing body. The check runs before a byte is emitted, so this side can never
/// send a violation.
pub fn encode_envelope(envelope: &Envelope) -> Result<Vec<u8>, EncodeError> {
    check(envelope).map_err(EncodeError::from)?;
    Ok(envelope.encode_to_vec())
}

/// Decodes the bytes of one WebSocket binary message into an `Envelope`.
///
/// Fails with [`DecodeError::TooLarge`] when the input is over [`MAX_MESSAGE_BYTES`], before
/// a single byte is parsed. Then the pre-scan, which allocates nothing, fails with
/// [`DecodeError::LimitViolation`] on a length or a count over its cap, with
/// [`DecodeError::UnknownMessage`] when there is no known body, and with
/// [`DecodeError::ProtocolViolation`] on bytes that break the grammar. Only then does prost
/// parse, so what it allocates is bounded by the limits table; the decoded values then pass
/// the same checks as on encode. Never panics on any input.
pub fn decode_envelope(bytes: &[u8]) -> Result<Envelope, DecodeError> {
    if bytes.len() > MAX_MESSAGE_BYTES {
        return Err(DecodeError::TooLarge);
    }
    prescan::envelope(bytes)?;
    let envelope = Envelope::decode(bytes)?;
    check(&envelope)?;
    Ok(envelope)
}

/// The width/height field names a size violation can be reported under, kept as pairs so a
/// `cap_size` call stays one line in [`check`].
const SURFACE_NEW_SIZE: (&str, &str) = ("surface_new.size.width", "surface_new.size.height");
/// The size of the positioner of a [`Body::SurfaceNew`] popup.
const POSITIONER_SIZE: (&str, &str) = (
    "surface_new.positioner.size.width",
    "surface_new.positioner.size.height",
);
/// The size of a [`Body::ResizeAsk`].
const RESIZE_ASK_SIZE: (&str, &str) = ("resize_ask.size.width", "resize_ask.size.height");
/// The size of a [`Body::Configure`].
const CONFIGURE_SIZE: (&str, &str) = ("configure.size.width", "configure.size.height");
/// The size of a [`Body::ConfigureAck`].
const CONFIGURE_ACK_SIZE: (&str, &str) = ("configure_ack.size.width", "configure_ack.size.height");

/// The limits table, the value rules and the closed enums as one predicate: the error names
/// the first broken rule.
///
/// One arm per wire message; a message with nothing to check has its arm spelled out anyway,
/// so a new message added to the `.proto` fails this match and forces a decision here.
fn check(envelope: &Envelope) -> Result<(), Violation> {
    let Some(body) = envelope.body.as_ref() else {
        return Err(Violation::NoBody);
    };
    match body {
        Body::Hello(m) => {
            cap_str(&m.client_name, MAX_CLIENT_NAME_BYTES, "hello.client_name")?;
            cap_bytes(&m.stream_token, MAX_TOKEN_BYTES, "hello.stream_token")?;
            cap_count(m.codecs.len(), MAX_CODECS_OFFERED, "hello.codecs")?;
        }
        Body::HelloReply(m) => {
            cap_str(
                &m.session_id,
                MAX_SESSION_ID_BYTES,
                "hello_reply.session_id",
            )?;
            cap_count(m.codecs.len(), MAX_CODECS_OFFERED, "hello_reply.codecs")?;
        }
        Body::Bye(m) => {
            closed::<ByeReason>(m.reason, "bye.reason")?;
            cap_str(&m.text, MAX_BYE_TEXT_BYTES, "bye.text")?;
        }
        Body::ServerError(m) => cap_str(&m.text, MAX_ERROR_TEXT_BYTES, "server_error.text")?,
        Body::SurfaceNew(m) => check_surface_new(m)?,
        Body::SurfaceGone(m) => closed::<SurfaceGoneReason>(m.reason, "surface_gone.reason")?,
        Body::SurfaceMetadata(m) => {
            if let Some(title) = m.title.as_ref() {
                cap_str(title, MAX_TITLE_BYTES, "surface_metadata.title")?;
            }
            if let Some(app_id) = m.app_id.as_ref() {
                cap_str(app_id, MAX_APP_ID_BYTES, "surface_metadata.app_id")?;
            }
            if m.scale_120ths == Some(0) {
                return Err(Violation::Limit("surface_metadata.scale_120ths"));
            }
        }
        Body::ResizeAsk(m) => cap_size(m.size.as_ref(), RESIZE_ASK_SIZE)?,
        Body::Configure(m) => {
            // Serial 0 is never a host serial: it marks the server's ConfigureAck for a size
            // change the host did not configure (v0.md §4.2).
            if m.serial == 0 {
                return Err(Violation::Limit("configure.serial"));
            }
            cap_size(m.size.as_ref(), CONFIGURE_SIZE)?;
        }
        Body::ConfigureAck(m) => cap_size(m.size.as_ref(), CONFIGURE_ACK_SIZE)?,
        Body::Frame(m) => {
            cap_count(m.tiles.len(), MAX_TILES_PER_FRAME, "frame.tiles")?;
            for tile in &m.tiles {
                check_tile(tile)?;
            }
        }
        Body::CursorImage(m) => check_cursor(m)?,
        Body::PointerAxis(m) => {
            cap_steps(m.steps_x, "pointer_axis.steps_x")?;
            cap_steps(m.steps_y, "pointer_axis.steps_y")?;
        }
        Body::Key(m) => {
            if m.code.is_empty() || !m.code.is_ascii() || m.code.len() > MAX_KEY_CODE_BYTES {
                return Err(Violation::Limit("key.code"));
            }
        }
        Body::ClipboardSet(m) => cap_str(&m.text, MAX_CLIPBOARD_BYTES, "clipboard_set.text")?,
        Body::ClipboardText(m) => cap_str(&m.text, MAX_CLIPBOARD_BYTES, "clipboard_text.text")?,
        // Nothing to check: a bare id, plain numbers, or no fields at all.
        Body::FocusAsk(_)
        | Body::FrameAck(_)
        | Body::CursorGone(_)
        | Body::PointerMove(_)
        | Body::PointerButton(_)
        | Body::FocusNotify(_)
        | Body::BlurRelease(_)
        | Body::ClipboardAsk(_)
        | Body::CloseRequest(_) => {}
    }
    Ok(())
}

/// A SurfaceNew against its role, its sizes, its strings, its positioner and its scale.
fn check_surface_new(m: &SurfaceNew) -> Result<(), Violation> {
    closed::<Role>(m.role, "surface_new.role")?;
    cap_size(m.size.as_ref(), SURFACE_NEW_SIZE)?;
    cap_str(&m.title, MAX_TITLE_BYTES, "surface_new.title")?;
    cap_str(&m.app_id, MAX_APP_ID_BYTES, "surface_new.app_id")?;
    if let Some(positioner) = m.positioner.as_ref() {
        closed::<Anchor>(positioner.anchor, "surface_new.positioner.anchor")?;
        closed::<Anchor>(positioner.gravity, "surface_new.positioner.gravity")?;
        cap_size(positioner.size.as_ref(), POSITIONER_SIZE)?;
    }
    if m.scale_120ths == 0 {
        return Err(Violation::Limit("surface_new.scale_120ths"));
    }
    Ok(())
}

/// One tile of a Frame against its rows of the table.
fn check_tile(tile: &Tile) -> Result<(), Violation> {
    if let Some(rect) = tile.rect.as_ref() {
        cap_dim(rect.width, MAX_TILE_WIDTH, "tile.rect.width")?;
        cap_dim(rect.height, MAX_TILE_HEIGHT, "tile.rect.height")?;
    }
    if tile.codec == 0 {
        return Err(Violation::Limit("tile.codec"));
    }
    cap_bytes(&tile.data, MAX_TILE_BYTES, "tile.data")
}

/// A cursor image against its caps, and its bytes against its size: exactly
/// `width * height * 4`, the rule the TypeScript decoder enforces too.
fn check_cursor(m: &CursorImage) -> Result<(), Violation> {
    const FIELD: &str = "cursor_image.argb_premultiplied";
    cap_dim(m.width, MAX_CURSOR_WIDTH, "cursor_image.width")?;
    cap_dim(m.height, MAX_CURSOR_HEIGHT, "cursor_image.height")?;
    cap_bytes(&m.argb_premultiplied, MAX_CURSOR_BYTES, FIELD)?;
    // Both sides are at most 128 after the caps above, so the product cannot overflow.
    let expected = u64::from(m.width) * u64::from(m.height) * 4;
    if u64::try_from(m.argb_premultiplied.len()).ok() != Some(expected) {
        return Err(Violation::Limit(FIELD));
    }
    Ok(())
}

/// A closed enum: the value must be one the generated enum `E` names. prost stores enum
/// fields as plain `i32` and accepts any value on decode, so this is where v0's closed sets
/// are enforced, in both directions.
fn closed<E: TryFrom<i32>>(value: i32, field: &'static str) -> Result<(), Violation> {
    if E::try_from(value).is_err() {
        return Err(Violation::Protocol(field));
    }
    Ok(())
}

/// A wheel-step cap: at most [`MAX_POINTER_AXIS_STEPS`] either way. `unsigned_abs` keeps
/// `i32::MIN` in range.
fn cap_steps(value: i32, field: &'static str) -> Result<(), Violation> {
    if value.unsigned_abs() > MAX_POINTER_AXIS_STEPS {
        return Err(Violation::Limit(field));
    }
    Ok(())
}

/// A string cap: bytes, not characters.
fn cap_str(value: &str, max: usize, field: &'static str) -> Result<(), Violation> {
    cap_count(value.len(), max, field)
}

/// A bytes cap.
fn cap_bytes(value: &[u8], max: usize, field: &'static str) -> Result<(), Violation> {
    cap_count(value.len(), max, field)
}

/// A count cap.
fn cap_count(len: usize, max: usize, field: &'static str) -> Result<(), Violation> {
    if len > max {
        return Err(Violation::Limit(field));
    }
    Ok(())
}

/// A pixel-dimension cap.
fn cap_dim(value: u32, max: u32, field: &'static str) -> Result<(), Violation> {
    if value > max {
        return Err(Violation::Limit(field));
    }
    Ok(())
}

/// A surface-size cap. An absent size carries no dimension and cannot break one.
fn cap_size(size: Option<&Size>, fields: (&'static str, &'static str)) -> Result<(), Violation> {
    if let Some(size) = size {
        cap_dim(size.width, MAX_SURFACE_WIDTH, fields.0)?;
        cap_dim(size.height, MAX_SURFACE_HEIGHT, fields.1)?;
    }
    Ok(())
}

