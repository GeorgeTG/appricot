    /// xorshift64* : a deterministic PRNG, no dependency needed. Truncation is the point: a
    /// PRNG hands out bits of its state.
    struct Rng(u64);

    #[allow(clippy::cast_possible_truncation)]
    impl Rng {
        fn next_u64(&mut self) -> u64 {
            let mut x = self.0;
            x ^= x >> 12;
            x ^= x << 25;
            x ^= x >> 27;
            self.0 = x;
            x.wrapping_mul(0x2545_f491_4f6c_dd1d)
        }

        fn byte(&mut self) -> u8 {
            (self.next_u64() >> 32) as u8
        }

        fn below(&mut self, n: usize) -> usize {
            (self.next_u64() % n as u64) as usize
        }
    }

    #[test]
    fn mutated_encodings_never_panic() {
        let corpus: Vec<Vec<u8>> = sample_kinds()
            .iter()
            .map(|env| encode_envelope(env).expect("sample encodes"))
            .collect();
        let mut rng = Rng(0x1234_5678_9abc_def0);
        let mut stayed_valid = 0usize;
        for _ in 0..10_000 {
            let base = &corpus[rng.below(corpus.len())];
            let mut bytes = base.clone();
            for _ in 0..=rng.below(4) {
                match rng.below(5) {
                    0 => {
                        let i = rng.below(bytes.len());
                        bytes[i] ^= 1 << rng.below(8);
                    }
                    1 => {
                        let i = rng.below(bytes.len());
                        bytes[i] = rng.byte();
                    }
                    2 => {
                        if bytes.len() > 1 {
                            bytes.truncate(1 + rng.below(bytes.len() - 1));
                        }
                    }
                    3 => {
                        for _ in 0..rng.below(16) {
                            bytes.push(rng.byte());
                        }
                    }
                    _ => {
                        let (a, b) = (rng.below(bytes.len()), rng.below(bytes.len()));
                        bytes.swap(a, b);
                    }
                }
            }
            // A mutation can land on another valid message; it must still re-encode.
            if let Ok(env) = decode_envelope(&bytes) {
                stayed_valid += 1;
                encode_envelope(&env).expect("decoded means valid, so encode works");
            }
        }
        assert!(
            stayed_valid > 0,
            "the corpus is valid; some mutation survives"
        );
    }

