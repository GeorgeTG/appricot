    /// One refused envelope: decode names `field`, encode refuses to emit it.
    fn expect_refused(env: &Envelope, field: &'static str) {
        let err = decode_envelope(&raw_bytes(env)).expect_err("must not decode");
        assert!(
            matches!(&err, DecodeError::LimitViolation { field: f } if *f == field),
            "decode: wrong violation for {field}: {err:?}"
        );
        assert_eq!(
            encode_envelope(env),
            Err(EncodeError::LimitViolation { field }),
            "encode: this side must refuse to emit it"
        );
        assert!(validate_envelope(env).is_err());
    }

