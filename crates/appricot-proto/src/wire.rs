//! The v0 wire messages and the Envelope codec.
//!
//! [`Envelope`] and every message type it can carry are generated at build time from the
//! frozen `proto/appricot/v0/wire.proto` (see `build.rs`) and re-exported flat here: build a
//! message, wrap it in [`Envelope`] with [`Body`], and hand it to the codec. The codec adds
//! the limits table of [`crate::limits`] and the v0 wire rules as a gate on both directions:
//!
//! - [`encode_envelope`] refuses to emit a message with a field over its cap, or with a value
//!   v0 does not define, so a violation can never leave this side.
//! - [`decode_envelope`] refuses input over [`MAX_MESSAGE_BYTES`] before parsing anything.
//!   It then runs a pre-scan over the raw bytes that allocates nothing: every length and
//!   every count is compared with its cap there, at cap + 1, before prost builds a single
//!   element or copies a single string. Only then does prost parse, and the same validation
//!   as on encode runs over the decoded values.
//! - [`validate_envelope`] runs the validation on its own, for callers holding an
//!   already-decoded [`Envelope`].
//!
//! The accepted set is the TypeScript mirror's, exactly (v0.md §1): an unknown field inside a
//! known message is skipped; an envelope with no body, an unknown body or a second body is
//! refused; an enum value v0 does not define is refused; a varint over 32 bits on a known
//! field is refused; a singular field that appears twice is refused.
//!
//! Encoding is deterministic: fields are emitted in field-number order, so
//! `encode(decode(bytes))` of a well-formed message is byte-identical to `bytes`. The
//! shared test vectors in `testdata/vectors.json` (regenerated by `tests/vectors.rs`) pin
//! those bytes, and the bytes both codecs must refuse, for the TypeScript mirror.
//!
//! Every string that arrives through these messages is untrusted text: a client renders it
//! as text, never as markup or a navigation (docs/adr/0003). The codec bounds it; what a
//! caller does with it is the caller's rule.

/// The generated `appricot.v0` package, straight from prost.
